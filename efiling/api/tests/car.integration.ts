import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { rm, rename } from 'node:fs/promises';
import dotenv from 'dotenv';
import { PrismaClient } from '@prisma/client';
import request from 'supertest';

test('CAR/NCR workflow preserves permissions, revisions, evidence and invalid transition guards', async () => {
  const root = fileURLToPath(new URL('../../', import.meta.url));
  dotenv.config({ path: resolve(root, '.env'), quiet: true });
  const original = process.env.DATABASE_URL!;
  const schema = `car_test_${randomUUID().replaceAll('-', '')}`;
  const storage = resolve(root, '.local', schema);
  const url = new URL(original); url.searchParams.set('schema', schema);
  process.env.DATABASE_URL = url.toString(); process.env.RECORD_STORAGE_DIR = storage;
  const admin = new PrismaClient({ datasourceUrl: original });
  let disconnect: (() => Promise<void>) | undefined;
  try {
    await admin.$executeRawUnsafe(`CREATE SCHEMA "${schema}"`);
    const migration = spawnSync(process.execPath, ['scripts/prisma.mjs', 'migrate', 'deploy'], { cwd: root, env: process.env, encoding: 'utf8' });
    assert.equal(migration.status, 0, migration.stderr);
    const { seedDemo } = await import('../../scripts/seed-demo.js');
    const { database, disconnectDatabase } = await import('../src/lib/prisma.js');
    disconnect = disconnectDatabase; await seedDemo();
    const { createApp } = await import('../src/app.js');
    const app = createApp(async () => {}), agent = request.agent(app), db = database();
    const login = (who: string) => agent.post('/api/auth/login').set('X-EFiling-Client', 'web').send({ email: `${who}@example.test`, password: 'Demo1234!' });
    const post = (path: string, body = {}) => agent.post(`/api/cars${path}`).set('X-EFiling-Client', 'web').send(body);
    const users = await db.user.findMany();
    const uid = (name: string) => users.find(u => u.username === name)!.id;
    const department = await db.department.findFirstOrThrow();
    const auditorDepartment = await db.department.create({ data: { code: 'TEST-AUDIT', nameTh: 'กลุ่มงานผู้ตรวจสำหรับทดสอบ' } });
    await db.user.update({ where: { id: uid('auditor') }, data: { departmentId: auditorDepartment.id } });
    await db.user.update({ where: { id: uid('carowner') }, data: { departmentId: department.id } });
    const finding = await db.finding.create({ data: { source: 'INTERNAL_AUDIT', findingType: 'NONCONFORMITY', severity: 'MINOR', description: 'พบความไม่สอดคล้องจากการตรวจ', violatedRequirement: '7.5', identifiedDate: new Date(), identifiedById: uid('auditor'), departmentId: department.id } });
    await request(app).get('/api/cars').expect(401);
    await login('reader'); await agent.get('/api/cars').expect(403);
    await login('dcc');
    const body = { findingId: finding.id, ownerUserId: uid('carowner'), departmentId: department.id, overallDueDate: '2026-10-30' };
    await post('', { ...body, overallDueDate: '2026-02-30' }).expect(400);
    const race = await Promise.all([post('', body), post('', body)]);
    assert.deepEqual(race.map(r => r.status).sort(), [201, 409]);
    const id = race.find(r => r.status === 201)!.body.id;
    assert.equal((await db.correctiveRequest.findUniqueOrThrow({ where: { id } })).requestType, 'CAR');
    await post(`/${id}/actions`, { action: 'start' }).expect(403);
    await login('assistant'); await agent.get(`/api/cars/${id}`).expect(403);
    await login('carowner');
    await agent.get(`/api/cars/${randomUUID()}`).expect(403);
    await post(`/${id}/actions`, { action: 'submit-plan' }).expect(409);
    const starts = await Promise.all([post(`/${id}/actions`, { action: 'start' }), post(`/${id}/actions`, { action: 'start' })]);
    assert.deepEqual(starts.map(r => r.status).sort(), [200, 409]);
    await post(`/${id}/actions`, { action: 'correction', detail: '' }).expect(400);
    await post(`/${id}/actions`, { action: 'correction', detail: 'นำเอกสารเก่าออกจากจุดใช้งาน' }).expect(200);
    const plan = { action: 'submit-plan', rootCause: 'ไม่มีขั้นตรวจฉบับ', technique: '5 Whys', correctiveSummary: 'เพิ่มขั้นตรวจ', preventiveSummary: 'ทบทวนจุดใช้งาน', activities: [{ kind: 'CORRECTIVE', description: 'ตรวจฉบับที่ใช้งาน', responsibleUserId: uid('carowner'), dueDate: '2026-10-20' }] };
    await post(`/${id}/actions`, { ...plan, action: 'save-plan', activities: [{ description: 'ร่างกิจกรรมยังไม่ครบ' }] }).expect(200);
    const draftResponse = await agent.get(`/api/cars/${id}`).expect(200);
    assert.equal(draftResponse.body.request.currentStatus, 'ANALYSIS_PLANNING');
    assert.equal(draftResponse.body.request.planDraft.activities[0].description, 'ร่างกิจกรรมยังไม่ครบ');
    await post(`/${id}/actions`, { ...plan, activities: [{ ...plan.activities[0], dueDate: '' }] }).expect(400);
    await post(`/${id}/actions`, plan).expect(200);
    await post(`/${id}/actions`, { action: 'approve' }).expect(403);
    await post(`/${id}/actions`, { action: 'submit-verification' }).expect(409);
    await login('lead'); await post(`/${id}/actions`, { action: 'approve' }).expect(403);
    await login('qmr');
    await post(`/${id}/actions`, { action: 'reject', reason: '' }).expect(400);
    await post(`/${id}/actions`, { action: 'reject', reason: 'ขอรายละเอียดเพิ่ม' }).expect(200);
    await login('carowner'); await post(`/${id}/actions`, plan).expect(200);
    await login('qmr');
    const submitted = await db.actionPlan.findFirstOrThrow({ where: { requestId: id, isCurrent: true } });
    await db.actionPlan.update({ where: { id: submitted.id }, data: { submittedById: uid('qmr') } });
    await post(`/${id}/actions`, { action: 'approve' }).expect(403);
    await db.actionPlan.update({ where: { id: submitted.id }, data: { submittedById: uid('carowner') } });
    await post(`/${id}/actions`, { action: 'approve' }).expect(200);
    await login('carowner'); await post(`/${id}/actions`, { action: 'submit-verification' }).expect(400);
    const current = await db.actionPlan.findFirstOrThrow({ where: { requestId: id, isCurrent: true }, include: { activities: true } });
    assert.equal(current.revision, 2);
    const activityId = current.activities[0].id;
    const pdf = Buffer.from('%PDF-1.4\n1 0 obj<</Type/Catalog>>endobj\n%%EOF\n');
    await agent.post(`/api/cars/${id}/activities/${activityId}/result`).set('X-EFiling-Client', 'web').field('resultNote', 'ไฟล์ปลอม').attach('files', Buffer.from('not a pdf'), 'fake.pdf').expect(400);
    assert.equal(await db.evidence.count({ where: { requestId: id } }), 0);
    await agent.post(`/api/cars/${id}/activities/${activityId}/result`).set('X-EFiling-Client', 'web').field('resultNote', 'ดำเนินการครบแล้ว').attach('files', pdf, 'proof.pdf').expect(200);
    const proof = await db.evidence.findFirstOrThrow({ where: { requestId: id } });
    await agent.get(`/api/cars/${id}/evidence/${proof.id}`).expect(200);
    await login('assistant'); await agent.get(`/api/cars/${id}/evidence/${proof.id}`).expect(403);
    await login('carowner');
    const proofPath = resolve(storage, proof.storagePath);
    await rename(proofPath, `${proofPath}.missing`);
    await post(`/${id}/actions`, { action: 'submit-verification' }).expect(409);
    assert.equal((await db.correctiveRequest.findUniqueOrThrow({ where: { id } })).currentStatus, 'IMPLEMENTING');
    await rename(`${proofPath}.missing`, proofPath);
    await post(`/${id}/actions`, { action: 'submit-verification' }).expect(200);
    await post(`/${id}/actions`, { action: 'verify-pass', reason: 'ตรวจเอง' }).expect(403);
    await login('auditor');
    await post(`/${id}/actions`, { action: 'verify-pass', reason: '' }).expect(400);
    await db.actionPlanActivity.update({ where: { id: activityId }, data: { responsibleUserId: uid('auditor') } });
    await post(`/${id}/actions`, { action: 'verify-pass', reason: 'ตรวจงานกิจกรรมตนเอง' }).expect(403);
    assert.equal(await db.verification.count({ where: { requestId: id } }), 0);
    const selfReview = await agent.get(`/api/cars/${id}`).expect(200);
    assert.ok(!selfReview.body.actions.includes('verify-pass'));
    await db.actionPlanActivity.update({ where: { id: activityId }, data: { responsibleUserId: uid('carowner') } });
    await db.correctiveRequest.update({ where: { id }, data: { ownerUserId: uid('auditor') } });
    await post(`/${id}/actions`, { action: 'verify-pass', reason: 'ผู้แก้ตรวจเอง' }).expect(403);
    await db.correctiveRequest.update({ where: { id }, data: { ownerUserId: uid('carowner') } });
    await post(`/${id}/actions`, { action: 'verify-fail', reason: 'ยังเกิดซ้ำ' }).expect(200);
    assert.equal((await db.correctiveRequest.findUniqueOrThrow({ where: { id } })).currentStatus, 'ANALYSIS_PLANNING');
    await login('carowner'); await post(`/${id}/actions`, plan).expect(200);
    await login('qmr'); await post(`/${id}/actions`, { action: 'approve' }).expect(200);
    await login('carowner'); await post(`/${id}/actions`, { action: 'submit-verification' }).expect(400);
    const next = await db.actionPlan.findFirstOrThrow({ where: { requestId: id, isCurrent: true }, include: { activities: true } });
    await agent.post(`/api/cars/${id}/activities/${next.activities[0].id}/result`).set('X-EFiling-Client', 'web').field('resultNote', 'แก้สาเหตุใหม่').attach('files', pdf, 'new-proof.pdf').expect(200);
    await post(`/${id}/actions`, { action: 'submit-verification' }).expect(200);
    await login('auditor'); await post(`/${id}/actions`, { action: 'verify-pass', reason: 'ทวนสอบแล้วไม่เกิดซ้ำ' }).expect(200);
    await login('qmr'); await post(`/${id}/actions`, { action: 'close' }).expect(409);
    assert.equal((await db.correctiveRequest.findUniqueOrThrow({ where: { id } })).currentStatus, 'PENDING_CLOSURE');
    assert.equal(await db.actionPlan.count({ where: { requestId: id } }), 3);
    assert.ok(await db.auditEvent.count({ where: { entityId: id, action: 'PERMISSION_DENIED' } }));
    assert.notEqual((await db.user.findUniqueOrThrow({ where: { id: uid('auditor') } })).departmentId, department.id);
    await login('auditor');
    const ncrFinding = await agent.post('/api/audit/findings').set('X-EFiling-Client', 'web')
      .field('source', 'MANAGEMENT_REVIEW').field('findingType', 'NONCONFORMITY').field('severity', 'MINOR')
      .field('description', 'ทบทวนระบบพบความไม่สอดคล้อง').field('violatedRequirement', '9.3')
      .field('identifiedDate', '2026-09-21').attach('files', pdf, 'management-review-proof.pdf').expect(201);
    assert.equal(ncrFinding.body.identifiedById, uid('auditor'));
    await login('dcc'); const ncr = await post('', { ...body, findingId: ncrFinding.body.id }).expect(201);
    assert.equal(ncr.body.requestType, 'NCR');
    assert.notEqual(ncr.body.requestNo, (await db.correctiveRequest.findUniqueOrThrow({ where: { id } })).requestNo);
    await login('carowner');
    await post(`/${ncr.body.id}/actions`, { action: 'start' }).expect(200);
    await post(`/${ncr.body.id}/actions`, { action: 'correction', detail: 'ควบคุมผลกระทบ' }).expect(200);
    await post(`/${ncr.body.id}/actions`, { ...plan, correctiveSummary: '', preventiveSummary: '' }).expect(200);
    await login('qmr'); await post(`/${ncr.body.id}/actions`, { action: 'approve' }).expect(200);
    assert.equal((await db.correctiveRequest.findUniqueOrThrow({ where: { id: ncr.body.id } })).currentStatus, 'IMPLEMENTING');
    await login('carowner');
    const recordType = await db.recordType.findFirstOrThrow();
    const qualityRecord = await db.qualityRecord.create({ data: { title: 'บันทึกผลการแก้ไข', recordDate: new Date(), recordTypeId: recordType.id, ownerUserId: uid('carowner'), createdById: uid('carowner') } });
    await db.evidence.update({ where: { id: proof.id }, data: { recordId: qualityRecord.id } });
    const ncrPlan = await db.actionPlan.findFirstOrThrow({ where: { requestId: ncr.body.id, isCurrent: true }, include: { activities: true } });
    await agent.post(`/api/cars/${ncr.body.id}/activities/${ncrPlan.activities[0].id}/result`).set('X-EFiling-Client', 'web').field('resultNote', 'ผลตามบันทึก').field('recordId', qualityRecord.id).expect(200);
    await rename(proofPath, `${proofPath}.missing`);
    await post(`/${ncr.body.id}/actions`, { action: 'submit-verification' }).expect(409);
    await rename(`${proofPath}.missing`, proofPath);
    await post(`/${ncr.body.id}/actions`, { action: 'submit-verification' }).expect(200);
    assert.equal((await db.evidence.findUniqueOrThrow({ where: { id: proof.id } })).activityId, activityId);
    await post(`/${ncr.body.id}/actions`, { action: 'verify-pass', reason: 'ผู้แก้ไขตรวจเอง' }).expect(403);
    await login('auditor');
    const verificationView = await agent.get(`/api/cars/${ncr.body.id}`).expect(200);
    assert.equal(verificationView.body.verificationBlocked, false);
    assert.ok(verificationView.body.actions.includes('verify-pass'));
    await post(`/${ncr.body.id}/actions`, { action: 'verify-pass', reason: 'ตรวจซ้ำแล้วการแก้ไขมีประสิทธิผล' }).expect(200);
    assert.equal((await db.correctiveRequest.findUniqueOrThrow({ where: { id: ncr.body.id } })).currentStatus, 'PENDING_CLOSURE');
    assert.equal(await db.verification.count({ where: { requestId: ncr.body.id, result: 'EFFECTIVE', verifiedById: uid('auditor') } }), 1);
    await login('qmr'); await post(`/${ncr.body.id}/actions`, { action: 'close' }).expect(409);
    await login('dcc');
    const external = await db.finding.create({ data: { source: 'EXTERNAL_AUDIT', findingType: 'NONCONFORMITY', severity: 'MINOR', description: 'ข้อบกพร่องจากภายนอก', violatedRequirement: '7.5', identifiedDate: new Date(), identifiedById: uid('dcc') } });
    await post('', { ...body, findingId: external.id }).expect(409);
    await db.finding.update({ where: { id: external.id }, data: { source: 'MANAGEMENT_REVIEW', findingType: 'OBSERVATION' } });
    await post('', { ...body, findingId: external.id }).expect(409);
    assert.equal(await db.correctiveRequest.count(), 2);
  } finally {
    if (disconnect) await disconnect();
    await admin.$executeRawUnsafe(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`); await admin.$disconnect();
    await rm(storage, { recursive: true, force: true });
  }
});
