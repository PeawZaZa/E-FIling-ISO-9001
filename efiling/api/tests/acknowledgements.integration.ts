import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { resolve, relative } from 'node:path';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import dotenv from 'dotenv';
import { PrismaClient } from '@prisma/client';
import request from 'supertest';

test('acknowledgements: DCC assigns readable published versions and recipients confirm only their own version', async () => {
  const root = fileURLToPath(new URL('../../', import.meta.url));
  dotenv.config({ path: resolve(root, '.env'), quiet: true });
  const original = process.env.DATABASE_URL!;
  assert.ok(original);
  const schema = `ack_test_${randomUUID().replaceAll('-', '')}`;
  const storage = resolve(root, '.local', schema);
  const url = new URL(original);
  url.searchParams.set('schema', schema);
  process.env.DATABASE_URL = url.toString();
  process.env.DOCUMENT_STORAGE_DIR = storage;
  const admin = new PrismaClient({ datasourceUrl: original });
  let disconnect: (() => Promise<void>) | undefined;
  try {
    await admin.$executeRawUnsafe(`CREATE SCHEMA "${schema}"`);
    const migrated = spawnSync(process.execPath, ['scripts/prisma.mjs', 'migrate', 'deploy'], { cwd: root, env: process.env, encoding: 'utf8' });
    assert.equal(migrated.status, 0, migrated.stderr + migrated.stdout);
    const { seedDemo } = await import('../../scripts/seed-demo.js');
    await seedDemo();
    const { database, disconnectDatabase } = await import('../src/lib/prisma.js');
    disconnect = disconnectDatabase;
    const db = database();
    const { dbUserId } = await import('../src/services/documentRules.js');
    const { createApp } = await import('../src/app.js');
    const app = createApp(async () => {});
    const agents: Record<string, ReturnType<typeof request.agent>> = {};
    for (const who of ['dcc', 'owner', 'reader', 'auditor', 'dean', 'deputy']) {
      agents[who] = request.agent(app);
      await agents[who].post('/api/auth/login').set('X-EFiling-Client', 'web').send({ email: `${who}@example.test`, password: 'Demo1234!' }).expect(200);
    }
    const pdf = Buffer.from('%PDF-1.4\nAcknowledgement fixture\n%%EOF');
    await mkdir(storage, { recursive: true });
    async function version(code: string, docType: string, withFile = true) {
      const document = await db.document.create({ data: { documentCode: code, title: `Title ${code}`, docType,
        versions: { create: { issueNo: 1, revisionNo: 0, status: 'DOC_PUBLISHED', reviewStatus: 'VERIFIED', effectiveDate: new Date('2026-09-20') } } }, include: { versions: true } });
      const item = document.versions[0];
      if (withFile) {
        const key = `${randomUUID()}.pdf`;
        await writeFile(resolve(storage, key), pdf);
        await db.documentFile.create({ data: { versionId: item.id, fileName: 'read.pdf', mimeType: 'application/pdf', sizeBytes: pdf.length, storagePath: key, sha256: randomUUID().replaceAll('-', '').padEnd(64, '0'), uploadedById: dbUserId('dcc') } });
      }
      return item.id;
    }
    const qp = await version('QP-2301-7001', 'QP');
    const qm = await version('QM-2301-70', 'QM');
    const noFile = await version('QP-2301-7002', 'QP', false);
    const options = await agents.dcc.get('/api/acknowledgements/options').expect(200);
    assert.ok(options.body.versions.some((v: { id: string }) => v.id === qp));
    assert.ok(options.body.users.some((u: { id: string }) => u.id === dbUserId('reader')));
    assert.ok(!options.body.users.some((u: { id: string }) => u.id === dbUserId('auditor')));
    assert.ok(!options.body.versions.some((v: { id: string }) => v.id === noFile));
    await agents.owner.get('/api/acknowledgements/options').expect(403);
    await agents.owner.get(`/api/acknowledgements/versions/${qp}`).expect(403);
    await agents.owner.post(`/api/acknowledgements/versions/${qp}/assign`).set('X-EFiling-Client', 'web').send({ assigneeIds: [dbUserId('reader')] }).expect(403);
    await agents.dcc.post(`/api/acknowledgements/versions/${qp}/assign`).set('X-EFiling-Client', 'web').send({ assigneeIds: [dbUserId('deputy')] }).expect(403);
    await agents.dcc.post(`/api/acknowledgements/versions/${qp}/assign`).set('X-EFiling-Client', 'web').send({ assigneeIds: [dbUserId('reader'), dbUserId('auditor')] }).expect(403);
    assert.equal(await db.acknowledgementAssignment.count({ where: { versionId: qp } }), 0);
    await agents.dcc.post(`/api/acknowledgements/versions/${qm}/assign`).set('X-EFiling-Client', 'web').send({ assigneeIds: [dbUserId('dean')] }).expect(200);
    await agents.dcc.post(`/api/acknowledgements/versions/${noFile}/assign`).set('X-EFiling-Client', 'web').send({ assigneeIds: [dbUserId('reader')] }).expect(409);
    await agents.dcc.post(`/api/acknowledgements/versions/${qp}/assign`).set('X-EFiling-Client', 'web').send({ assigneeIds: [dbUserId('reader'), dbUserId('owner')] }).expect(200);
    const assignment = await db.acknowledgementAssignment.findUniqueOrThrow({ where: { versionId_assigneeId: { versionId: qp, assigneeId: dbUserId('reader') } } });
    assert.equal(assignment.assignedById, dbUserId('dcc'));
    assert.equal(await db.acknowledgementAssignment.count({ where: { versionId: qp } }), 2);
    const mine = await agents.reader.get('/api/acknowledgements/mine').expect(200);
    assert.equal(mine.body.assignments.length, 1);
    assert.equal(mine.body.assignments[0].versionId, qp);
    assert.equal(mine.body.assignments[0].canConfirm, true);
    assert.ok(mine.body.assignments[0].fileId);
    await agents.owner.post(`/api/acknowledgements/${assignment.id}/confirm`).set('X-EFiling-Client', 'web').send({}).expect(403);
    await agents.auditor.post(`/api/acknowledgements/${assignment.id}/confirm`).set('X-EFiling-Client', 'web').send({}).expect(403);
    await agents.reader.post(`/api/acknowledgements/${assignment.id}/confirm`).set('X-EFiling-Client', 'web').send({}).expect(409);
    assert.equal(await db.acknowledgementConfirmation.count(), 0);
    assert.equal(await db.auditEvent.count({ where: { action: 'ACKNOWLEDGE' } }), 0);
    await agents.owner.get(`/api/documents/files/${mine.body.assignments[0].fileId}?download=1`).expect(200);
    await agents.reader.post(`/api/acknowledgements/${assignment.id}/confirm`).set('X-EFiling-Client', 'web').send({}).expect(409);
    const qmFile = await db.documentFile.findFirstOrThrow({ where: { versionId: qm } });
    await agents.reader.get(`/api/documents/files/${qmFile.id}?download=1`).expect(200);
    await agents.reader.post(`/api/acknowledgements/${assignment.id}/confirm`).set('X-EFiling-Client', 'web').send({}).expect(409);
    await agents.reader.get(`/api/documents/files/${mine.body.assignments[0].fileId}?download=1`).expect(200);
    assert.equal(await db.acknowledgementConfirmation.count(), 0);
    await agents.reader.post(`/api/acknowledgements/${assignment.id}/confirm`).set('X-EFiling-Client', 'web').send({}).expect(200);
    const first = await db.acknowledgementConfirmation.findUniqueOrThrow({ where: { assignmentId: assignment.id } });
    assert.equal(first.confirmedById, dbUserId('reader'));
    assert.equal(first.assignmentId, assignment.id);
    const accessEvent = await db.auditEvent.findFirstOrThrow({ where: { action: 'EXPORT', entityType: 'DocumentFile', entityId: mine.body.assignments[0].fileId, actorUserId: dbUserId('reader') }, orderBy: { occurredAt: 'desc' } });
    assert.deepEqual(accessEvent.afterValue, { versionId: qp });
    assert.ok(accessEvent.occurredAt.getTime() <= first.confirmedAt.getTime());
    const event = await db.auditEvent.findFirstOrThrow({ where: { entityType: 'AcknowledgementConfirmation', entityId: first.id } });
    assert.equal(event.actorUserId, dbUserId('reader'));
    assert.equal(event.actorRole, 'END_USER');
    assert.deepEqual(event.afterValue, { assignmentId: assignment.id, versionId: qp, confirmedById: dbUserId('reader') });
    assert.ok(event.occurredAt.getTime() >= first.confirmedAt.getTime());
    await agents.reader.post(`/api/acknowledgements/${assignment.id}/confirm`).set('X-EFiling-Client', 'web').send({}).expect(200);
    assert.equal(await db.acknowledgementConfirmation.count({ where: { assignmentId: assignment.id } }), 1);
    await agents.dcc.post(`/api/acknowledgements/versions/${qp}/assign`).set('X-EFiling-Client', 'web').send({ assigneeIds: [dbUserId('reader')] }).expect(200);
    const again = await db.acknowledgementConfirmation.findUniqueOrThrow({ where: { assignmentId: assignment.id } });
    assert.equal(again.confirmedAt.getTime(), first.confirmedAt.getTime());
    assert.equal(await db.auditEvent.count({ where: { entityType: 'AcknowledgementConfirmation', entityId: first.id } }), 1);
    const oldVersion = await version('QP-2301-7003', 'QP');
    await agents.dcc.post(`/api/acknowledgements/versions/${oldVersion}/assign`).set('X-EFiling-Client', 'web').send({ assigneeIds: [dbUserId('reader')] }).expect(200);
    const oldAssignment = await db.acknowledgementAssignment.findUniqueOrThrow({ where: { versionId_assigneeId: { versionId: oldVersion, assigneeId: dbUserId('reader') } } });
    await db.documentVersion.update({ where: { id: oldVersion }, data: { status: 'DOC_OBSOLETE' } });
    const after = await agents.reader.get('/api/acknowledgements/mine').expect(200);
    assert.equal(after.body.assignments.find((a: { id: string }) => a.id === oldAssignment.id).canConfirm, false);
    await agents.reader.post(`/api/acknowledgements/${oldAssignment.id}/confirm`).set('X-EFiling-Client', 'web').send({}).expect(409);
    const unavailable = await version('QP-2301-7004', 'QP');
    await agents.dcc.post(`/api/acknowledgements/versions/${unavailable}/assign`).set('X-EFiling-Client', 'web').send({ assigneeIds: [dbUserId('reader')] }).expect(200);
    const unavailableAssignment = await db.acknowledgementAssignment.findUniqueOrThrow({ where: { versionId_assigneeId: { versionId: unavailable, assigneeId: dbUserId('reader') } } });
    const unavailableFile = await db.documentFile.findFirstOrThrow({ where: { versionId: unavailable } });
    await rm(resolve(storage, unavailableFile.storagePath));
    await agents.reader.post(`/api/acknowledgements/${unavailableAssignment.id}/confirm`).set('X-EFiling-Client', 'web').send({}).expect(409);
    const disabled = await version('QP-2301-7005', 'QP');
    const disabledVersion = await db.documentVersion.findUniqueOrThrow({ where: { id: disabled } });
    await db.document.update({ where: { id: disabledVersion.documentId }, data: { isActive: false } });
    await agents.dcc.post(`/api/acknowledgements/versions/${disabled}/assign`).set('X-EFiling-Client', 'web').send({ assigneeIds: [dbUserId('reader')] }).expect(409);
    await db.user.update({ where: { id: dbUserId('owner') }, data: { isActive: false } });
    const inactive = await agents.dcc.get('/api/acknowledgements/options').expect(200);
    assert.ok(!inactive.body.users.some((u: { id: string }) => u.id === dbUserId('owner')));
    await agents.dcc.post(`/api/acknowledgements/versions/${qm}/assign`).set('X-EFiling-Client', 'web').send({ assigneeIds: [dbUserId('owner')] }).expect(403);
    await db.user.update({ where: { id: dbUserId('dcc') }, data: { isActive: false } });
    await agents.dcc.post(`/api/acknowledgements/versions/${qm}/assign`).set('X-EFiling-Client', 'web').send({ assigneeIds: [dbUserId('reader')] }).expect(403);
  } finally {
    await disconnect?.();
    await admin.$executeRawUnsafe(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
    await admin.$disconnect();
    assert.equal(relative(resolve(root, '.local'), storage), schema);
    await rm(storage, { recursive: true, force: true });
    process.env.DATABASE_URL = original;
    delete process.env.DOCUMENT_STORAGE_DIR;
  }
});
