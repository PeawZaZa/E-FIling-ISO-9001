/**
 * หาว่าเมนูรายการใดคือรายการที่กำลังใช้งานอยู่
 *
 * ทำไมไม่ใช้ isActive ของ NavLink ตรง ๆ: NavLink ถือว่าลิงก์ทำงานอยู่
 * เมื่อเส้นทางปัจจุบัน "ขึ้นต้นด้วย" เส้นทางของลิงก์ เมนูของเราจึงติดสว่าง
 * พร้อมกันสองรายการ เพราะมีเส้นทางที่ซ้อนกันอยู่สามคู่
 * เช่น /documents กับ /documents/new
 *
 * การใส่ end ให้ทุกลิงก์แก้ปัญหานี้ได้ แต่สร้างปัญหาใหม่ คือเมื่อเปิด
 * หน้ารายละเอียดที่ไม่มีเมนูของตัวเอง เช่น /cars/<รหัสใบคำร้อง>
 * จะไม่มีเมนูใดสว่างเลย ผู้ใช้จึงไม่รู้ว่าตัวเองอยู่ส่วนไหนของระบบ
 *
 * กฎที่ถูกต้องคือ เส้นทางที่ "เจาะจงที่สุด" เท่านั้นที่ทำงานอยู่
 */
export function findActivePath(
  paths: readonly string[],
  currentPath: string,
): string | undefined {
  return paths
    .filter((path) => currentPath === path || currentPath.startsWith(`${path}/`))
    .sort((a, b) => b.length - a.length)[0];
}
